#!/usr/bin/env python3
"""
Convert Doxygen XML documentation to Quarto (.qmd) files for SAS macros.

This script parses the XML files generated by Doxygen and creates individual
Quarto markdown files suitable for inclusion in a Quarto book.

Usage:
    python xml_to_qmd.py [--xml-dir docs/xml] [--output-dir quarto/macros]
"""

import xml.etree.ElementTree as ET
import os
import argparse
from pathlib import Path
from typing import Dict, List, Optional, Tuple


class DoxygenXMLParser:
    """Parse Doxygen XML files for SAS macro documentation."""

    def __init__(self, xml_dir: str):
        self.xml_dir = Path(xml_dir)

    def get_all_file_xmls(self) -> List[Path]:
        """Get all XML files for SAS macros (exclude index.xml)."""
        return [f for f in self.xml_dir.glob("*.xml")
                if f.name != "index.xml" and "_8sas.xml" in f.name]

    def parse_file(self, xml_file: Path) -> Optional[Dict]:
        """Parse a single XML file and extract macro documentation."""
        try:
            tree = ET.parse(xml_file)
            root = tree.getroot()

            # Find the compounddef element (file definition)
            compounddef = root.find(".//compounddef[@kind='file']")
            if compounddef is None:
                return None

            # Extract basic file info
            filename = compounddef.find("compoundname").text if compounddef.find("compoundname") is not None else ""
            brief = self._get_text(compounddef.find("briefdescription"))
            detailed = self._get_text(compounddef.find("detaileddescription"))

            # Extract macro name (without .sas extension)
            macro_name = filename.replace(".sas", "") if filename else xml_file.stem.replace("_8sas", "")

            # Parse parameters, examples, author, date from detailed description
            params = self._extract_parameters(compounddef)
            returns = self._extract_return(compounddef)
            examples = self._extract_examples(compounddef)
            author, date = self._extract_metadata(compounddef)
            remarks = self._extract_remarks(compounddef)

            return {
                "filename": filename,
                "macro_name": macro_name,
                "brief": brief,
                "detailed": detailed,
                "parameters": params,
                "returns": returns,
                "examples": examples,
                "author": author,
                "date": date,
                "remarks": remarks
            }

        except Exception as e:
            print(f"Error parsing {xml_file}: {e}")
            return None

    def _get_text(self, element, exclude_tags=None) -> str:
        """Extract all text content from an XML element, excluding certain tags."""
        if element is None:
            return ""

        if exclude_tags is None:
            exclude_tags = {'parameterlist', 'simplesect', 'programlisting'}

        text_parts = []

        # Process only direct para children to avoid pulling in nested sections
        for para in element.findall("para"):
            # Skip paras that are inside excluded elements
            skip = False
            for parent in element.iter():
                if parent.tag in exclude_tags:
                    if para in list(parent.iter()):
                        skip = True
                        break

            if not skip:
                para_text = self._get_para_text(para)
                if para_text:
                    text_parts.append(para_text)

        return " ".join(text_parts)

    def _get_para_text(self, para) -> str:
        """Extract text from a single para element."""
        parts = []

        if para.text:
            parts.append(para.text.strip())

        for child in para:
            if child.tag in {'parameterlist', 'simplesect', 'programlisting'}:
                continue
            if child.text:
                parts.append(child.text.strip())
            if child.tail:
                parts.append(child.tail.strip())

        return " ".join([p for p in parts if p])

    def _extract_parameters(self, compounddef) -> List[Dict[str, str]]:
        """Extract parameter information."""
        params = []

        # Look for parameterlist in detaileddescription
        detailed = compounddef.find("detaileddescription")
        if detailed is not None:
            param_lists = detailed.findall(".//parameterlist[@kind='param']")
            for param_list in param_lists:
                for param_item in param_list.findall("parameteritem"):
                    param_name_elem = param_item.find(".//parametername")
                    param_desc_elem = param_item.find(".//parameterdescription")

                    if param_name_elem is not None:
                        param_name = param_name_elem.text or ""
                        param_desc = self._get_text(param_desc_elem) if param_desc_elem is not None else ""

                        # Extract Required/Optional/Default info
                        param_info = self._parse_param_description(param_desc)
                        params.append({
                            "name": param_name,
                            "description": param_info["description"],
                            "required": param_info["required"],
                            "default": param_info["default"]
                        })

        return params

    def _parse_param_description(self, desc: str) -> Dict[str, str]:
        """Parse parameter description to extract required/default info."""
        result = {
            "description": desc,
            "required": "",
            "default": ""
        }

        # Check for (Required), (Optional), or (Default: ...)
        if "(Required)" in desc:
            result["required"] = "Yes"
            result["description"] = desc.replace("(Required)", "").strip()
        elif "(Optional)" in desc:
            result["required"] = "No"
            result["description"] = desc.replace("(Optional)", "").strip()
        elif "Default:" in desc or "(Default:" in desc:
            result["required"] = "No"
            # Extract default value
            if "(Default:" in desc:
                parts = desc.split("(Default:")
                if len(parts) > 1:
                    default_part = parts[1].split(")")[0].strip()
                    result["default"] = default_part
                    result["description"] = parts[0].strip()
            elif "Default:" in desc:
                parts = desc.split("Default:")
                if len(parts) > 1:
                    default_part = parts[1].split(")")[0].split("(")[0].strip()
                    result["default"] = default_part
                    result["description"] = parts[0].strip()

        return result

    def _extract_return(self, compounddef) -> str:
        """Extract return value description."""
        detailed = compounddef.find("detaileddescription")
        if detailed is not None:
            # Look for simplesect with kind="return"
            return_sect = detailed.find(".//simplesect[@kind='return']")
            if return_sect is not None:
                return self._get_text(return_sect)
        return ""

    def _extract_examples(self, compounddef) -> List[str]:
        """Extract code examples."""
        examples = []
        detailed = compounddef.find("detaileddescription")
        if detailed is not None:
            # Look for simplesect with kind="par" and title containing "Example"
            for simplesect in detailed.findall(".//simplesect[@kind='par']"):
                title_elem = simplesect.find("title")
                if title_elem is not None and "Example" in (title_elem.text or ""):
                    # Found example section, now get the programlisting
                    for programlisting in simplesect.findall(".//programlisting"):
                        code_lines = []
                        for codeline in programlisting.findall("codeline"):
                            # Build complete line from all text content
                            line_text = self._extract_codeline_text(codeline)
                            if line_text:
                                code_lines.append(line_text)

                        if code_lines:
                            examples.append("\n".join(code_lines))

        return examples

    def _extract_codeline_text(self, codeline) -> str:
        """Extract complete text from a codeline element."""
        parts = []

        # Get text directly in codeline (before any children)
        if codeline.text:
            parts.append(codeline.text)

        # Iterate through all children and collect their text and tails
        for elem in codeline.iter():
            if elem == codeline:
                continue

            # Get text content of element
            if elem.text:
                parts.append(elem.text)

            # Get tail (text after the element's closing tag)
            if elem.tail:
                parts.append(elem.tail)

        # Join all parts and handle <sp/> tags (spaces)
        result = "".join(parts)
        # Replace special space markers if needed
        result = result.replace("  ", " ")  # Normalize multiple spaces

        return result.strip()

    def _extract_metadata(self, compounddef) -> Tuple[str, str]:
        """Extract author and date."""
        author = ""
        date = ""

        detailed = compounddef.find("detaileddescription")
        if detailed is not None:
            # Look for simplesect with kind="author"
            author_sect = detailed.find(".//simplesect[@kind='author']")
            if author_sect is not None:
                author = self._get_text(author_sect)

            # Look for simplesect with kind="date"
            date_sect = detailed.find(".//simplesect[@kind='date']")
            if date_sect is not None:
                date = self._get_text(date_sect)

        return author, date

    def _extract_remarks(self, compounddef) -> str:
        """Extract remarks/notes."""
        detailed = compounddef.find("detaileddescription")
        if detailed is not None:
            # Look for simplesect with kind="remark"
            remark_sect = detailed.find(".//simplesect[@kind='remark']")
            if remark_sect is not None:
                return self._get_text(remark_sect)
        return ""


class QuartoGenerator:
    """Generate Quarto markdown files from parsed Doxygen data."""

    def __init__(self, output_dir: str):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_qmd(self, macro_data: Dict) -> Path:
        """Generate a Quarto markdown file for a macro."""
        filename = f"{macro_data['macro_name']}.qmd"
        output_path = self.output_dir / filename

        with open(output_path, 'w') as f:
            # Write YAML header
            f.write("---\n")
            f.write(f"title: \"{macro_data['macro_name']}\"\n")
            if macro_data['author']:
                f.write(f"author: \"{macro_data['author']}\"\n")
            if macro_data['date']:
                f.write(f"date: \"{macro_data['date']}\"\n")
            f.write("---\n\n")

            # Write brief description
            if macro_data['brief']:
                f.write(f"## Description\n\n")
                f.write(f"{macro_data['brief']}\n\n")

            # Write detailed description
            if macro_data['detailed']:
                f.write(f"{macro_data['detailed']}\n\n")

            # Write parameters section
            if macro_data['parameters']:
                f.write("## Parameters\n\n")
                for param in macro_data['parameters']:
                    f.write(f"**`{param['name']}`**\n\n")
                    f.write(f": {param['description']}\n\n")

                    if param['required']:
                        f.write(f"  *Required:* {param['required']}\n\n")

                    if param['default']:
                        f.write(f"  *Default:* `{param['default']}`\n\n")

            # Write return value
            if macro_data['returns']:
                f.write("## Returns\n\n")
                f.write(f"{macro_data['returns']}\n\n")

            # Write examples
            if macro_data['examples']:
                f.write("## Examples\n\n")
                for example in macro_data['examples']:
                    f.write("```sas\n")
                    f.write(f"{example}\n")
                    f.write("```\n\n")

            # Write remarks
            if macro_data['remarks']:
                f.write("## Remarks\n\n")
                f.write(f"{macro_data['remarks']}\n\n")

        return output_path


def create_quarto_book_config(output_dir: Path, macro_files: List[str]):
    """Create a _quarto.yml configuration file for the book."""
    config_path = output_dir.parent / "_quarto.yml"

    # Sort macro files alphabetically
    macro_files_sorted = sorted(macro_files)

    with open(config_path, 'w') as f:
        f.write("project:\n")
        f.write("  type: book\n\n")
        f.write("book:\n")
        f.write("  title: \"Atorus SAS Macros Documentation\"\n")
        f.write("  author: \"Atorus Research\"\n")
        f.write("  chapters:\n")
        f.write("    - index.qmd\n")
        f.write("    - part: \"Global Macros\"\n")
        f.write("      chapters:\n")

        # Add global macros
        for macro_file in macro_files_sorted:
            if not macro_file.startswith(('jd', 'kd', 'kp', 'kq', 'ku', 'setup')):
                f.write(f"        - macros/{macro_file}\n")

        f.write("    - part: \"Study-Specific Macros\"\n")
        f.write("      chapters:\n")

        # Add study-specific macros
        for macro_file in macro_files_sorted:
            if macro_file.startswith(('jd', 'kd', 'kp', 'kq', 'ku', 'setup')):
                f.write(f"        - macros/{macro_file}\n")

        f.write("\nformat:\n")
        f.write("  html:\n")
        f.write("    theme: cosmo\n")
        f.write("    toc: true\n")
        f.write("    number-sections: false\n")

    print(f"Created Quarto book configuration: {config_path}")


def create_index_file(output_dir: Path):
    """Create an index.qmd file for the book."""
    index_path = output_dir.parent / "index.qmd"

    with open(index_path, 'w') as f:
        f.write("---\n")
        f.write("title: \"Atorus SAS Macros Documentation\"\n")
        f.write("---\n\n")
        f.write("# Welcome\n\n")
        f.write("This documentation provides comprehensive information about ")
        f.write("the SAS macros developed by Atorus Research for clinical trial data processing.\n\n")
        f.write("## About\n\n")
        f.write("These macros are designed to streamline common tasks in clinical trial data management, ")
        f.write("including:\n\n")
        f.write("- Data transformation and manipulation\n")
        f.write("- SDTM and ADaM dataset creation\n")
        f.write("- Quality control and validation\n")
        f.write("- Report generation\n\n")
        f.write("## Organization\n\n")
        f.write("The macros are organized into two categories:\n\n")
        f.write("- **Global Macros**: Reusable utilities applicable across multiple studies\n")
        f.write("- **Study-Specific Macros**: Specialized tools for specific study requirements\n\n")
        f.write("Use the navigation menu to browse individual macro documentation.\n")

    print(f"Created index file: {index_path}")


def main():
    """Main function to convert XML to Quarto files."""
    parser = argparse.ArgumentParser(
        description="Convert Doxygen XML to Quarto markdown files for SAS macros"
    )
    parser.add_argument(
        "--xml-dir",
        default="docs/xml",
        help="Directory containing Doxygen XML files (default: docs/xml)"
    )
    parser.add_argument(
        "--output-dir",
        default="quarto/macros",
        help="Output directory for Quarto files (default: quarto/macros)"
    )
    parser.add_argument(
        "--create-book-config",
        action="store_true",
        help="Create _quarto.yml configuration file for book"
    )

    args = parser.parse_args()

    # Initialize parser and generator
    xml_parser = DoxygenXMLParser(args.xml_dir)
    qmd_generator = QuartoGenerator(args.output_dir)

    # Get all XML files
    xml_files = xml_parser.get_all_file_xmls()
    print(f"Found {len(xml_files)} XML files to process")

    # Process each file
    generated_files = []
    for xml_file in xml_files:
        print(f"Processing {xml_file.name}...")
        macro_data = xml_parser.parse_file(xml_file)

        if macro_data:
            output_path = qmd_generator.generate_qmd(macro_data)
            generated_files.append(output_path.name)
            print(f"  → Generated {output_path}")
        else:
            print(f"  ✗ Skipped (no valid data)")

    print(f"\n✓ Successfully generated {len(generated_files)} Quarto files")

    # Create book configuration if requested
    if args.create_book_config:
        create_quarto_book_config(Path(args.output_dir), generated_files)
        create_index_file(Path(args.output_dir))
        print("\n✓ Created Quarto book configuration files")
        print(f"\nTo build the book, run:")
        print(f"  cd {Path(args.output_dir).parent}")
        print(f"  quarto render")


if __name__ == "__main__":
    main()
